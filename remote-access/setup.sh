#!/usr/bin/env bash
#
# remote-access/setup.sh — SSH + Remote Desktop from my iPhone over Tailscale, locked down.
#
#   ./setup.sh                run every step (idempotent; asks for sudo)
#   ./setup.sh --reconfigure  also redo Remote Desktop settings/password
#   ./setup.sh --print-guard  print the generated nftables guard and exit
#
# Run it from a terminal inside the Omarchy desktop (Remote Desktop needs the
# Wayland session), after ../setup.sh has linked the dotfiles and installed the
# plugins. Settings: peers.conf. Background: README.md in this folder.
#
# Steps:
#   1. packages: tailscale openssh ufw nftables, hypr-rdp (AUR)
#   2. Tailscale: enable the daemon, log in if needed
#   3. firewall: nftables guard (only loopback + allowed peers reach GUARDED_PORTS),
#      matching ufw rules, and removal of any "SSH from anywhere" ufw rules
#   4. SSH: key-only hardening, authorized_keys, sshd enabled
#   5. Remote Desktop: configure the kokd.remote-desktop plugin on this machine's
#      Tailscale address and turn it on
#
# Secrets never go in this repo: the RDP password is typed in (or generated and
# written to ~/rdp-iphone-password.txt, mode 600), and the plugin keeps it with its
# TLS key under ~/.config/omarchy-remote-desktop/ (mode 700).
set -euo pipefail

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=peers.conf
source "$HERE/peers.conf"
CTL="$HOME/.config/omarchy/plugins/kokd.remote-desktop/bin/remote-desktopctl"
reconfigure=0

info() { echo -e "\033[94m==>\033[0m $*" >&2; }
ok() { echo -e "  \033[92m✓\033[0m $*" >&2; }
warn() { echo -e "\033[0;33m$*\033[0m" >&2; }
die() {
	echo -e "\033[91;1m$*\033[0m" >&2
	exit 1
}

guard_nft() {
	local ports v4 v6
	ports=$(IFS=,; echo "${GUARDED_PORTS[*]}")
	echo "#!/usr/sbin/nft -f"
	echo "# Generated by ~/.dotfiles/remote-access/setup.sh from peers.conf; edit there, not here."
	echo "# Ports ${ports} only accept loopback and the listed Tailscale peers. Separate table,"
	echo "# evaluated before iptables/ufw/Tailscale (priority -10); a drop here is final."
	echo "table inet tailnet_guard"
	echo "delete table inet tailnet_guard"
	echo "table inet tailnet_guard {"
	echo "	chain input {"
	echo "		type filter hook input priority -10; policy accept;"
	echo "		tcp dport { ${ports//,/, } } jump guard"
	echo "	}"
	echo "	chain guard {"
	echo "		iifname \"lo\" return"
	for v4 in "${ALLOWED_V4[@]}"; do echo "		iifname \"tailscale0\" ip saddr $v4 return"; done
	for v6 in "${ALLOWED_V6[@]}"; do echo "		iifname \"tailscale0\" ip6 saddr $v6 return"; done
	echo "		counter drop"
	echo "	}"
	echo "}"
}

case ${1:-} in
--print-guard)
	guard_nft
	exit 0
	;;
--reconfigure) reconfigure=1 ;;
"") ;;
*) die "unknown argument: $1 (see the top of this file)" ;;
esac

[[ $EUID -ne 0 ]] || die "Run as your normal user, not root (it uses sudo where needed)."

# ── 1. Packages ──────────────────────────────────────────────────────────────
info "Packages"
omarchy pkg add tailscale openssh ufw nftables
omarchy pkg aur add hypr-rdp || die "Could not install hypr-rdp from the AUR."
command -v hypr-rdp >/dev/null || die "hypr-rdp is not on PATH."
ok "tailscale openssh ufw nftables hypr-rdp"

# ── 2. Tailscale ─────────────────────────────────────────────────────────────
info "Tailscale"
sudo systemctl enable --now tailscaled
if ! tailscale ip -4 >/dev/null 2>&1; then
	warn "  Not logged in: open the URL below and sign in to the same Tailscale account as the iPhone."
	sudo tailscale up
fi
TS_IP=$(tailscale ip -4 | head -1)
[[ $TS_IP == 100.* ]] || die "No Tailscale IPv4 address."
ok "this machine is $TS_IP"

# ── 3. Firewall ──────────────────────────────────────────────────────────────
# Tailscale's own iptables chain (ts-input) accepts everything on tailscale0
# before ufw sees it, so ufw alone cannot restrict tailnet peers. The nftables
# guard runs earlier and is what actually enforces "only these peers".
info "Firewall guard (nftables)"
tmp=$(mktemp)
guard_nft >"$tmp"
sudo nft -c -f "$tmp"
sudo install -Dm644 "$tmp" /etc/nftables.d/tailnet-guard.nft
rm -f "$tmp"
sudo install -Dm644 "$HERE/tailnet-guard.service" /etc/systemd/system/tailnet-guard.service
sudo systemctl daemon-reload
sudo systemctl enable tailnet-guard.service >/dev/null 2>&1
sudo systemctl restart tailnet-guard.service
ok "ports ${GUARDED_PORTS[*]} limited to loopback + ${ALLOWED_V4[*]} ${ALLOWED_V6[*]}"

info "ufw"
sudo ufw status | grep -q '^Status: active' || sudo ufw --force enable
for spec in "22/tcp" "22" "ssh" "in on tailscale0 to any port 22 proto tcp"; do
	# shellcheck disable=SC2086
	sudo ufw delete allow $spec >/dev/null 2>&1 || true
done
for port in "${GUARDED_PORTS[@]}"; do
	for peer in "${ALLOWED_V4[@]}" "${ALLOWED_V6[@]}"; do
		sudo ufw allow in on tailscale0 from "$peer" to any port "$port" proto tcp \
			comment "port $port from allowed Tailscale peer" >/dev/null
	done
done
ok "no SSH-from-anywhere rules; allowed peers only"

# ── 4. SSH ───────────────────────────────────────────────────────────────────
info "SSH"
tmp=$(mktemp)
sed "s/__USER__/$USER/g" "$HERE/sshd-hardening.conf" >"$tmp"
sudo install -Dm644 "$tmp" /etc/ssh/sshd_config.d/10-hardening.conf
rm -f "$tmp"
install -d -m700 "$HOME/.ssh"
touch "$HOME/.ssh/authorized_keys"
chmod 600 "$HOME/.ssh/authorized_keys"
while IFS= read -r key; do
	[[ -z $key || $key == \#* ]] && continue
	grep -qxF "$key" "$HOME/.ssh/authorized_keys" || echo "$key" >>"$HOME/.ssh/authorized_keys"
done <"$HERE/authorized_keys"
sudo sshd -t
sudo systemctl enable sshd >/dev/null 2>&1
sudo systemctl restart sshd
ok "key-only login for $USER; iPhone key authorized"

# ── 5. Remote Desktop ────────────────────────────────────────────────────────
info "Remote Desktop"
[[ -x $CTL || -f $CTL ]] || die "kokd.remote-desktop plugin missing: run omarchy-plugins/install-plugins.sh first."
[[ -n ${WAYLAND_DISPLAY:-} ]] || die "Run this from a terminal inside the Omarchy desktop."
omarchy plugin enable kokd.remote-desktop >/dev/null

current=$(python3 -c 'import json,sys
try: print(json.load(open(sys.argv[1])).get("address",""))
except Exception: print("")' "$HOME/.config/omarchy-remote-desktop/settings.json")

if ((reconfigure)) || [[ $current != "$TS_IP" || ! -f $HOME/.config/omarchy-remote-desktop/password ]]; then
	output=$RDP_OUTPUT
	if ! hyprctl monitors -j | python3 -c 'import json,sys; sys.exit(0 if any(m["name"]==sys.argv[1] for m in json.load(sys.stdin)) else 1)' "$output"; then
		output=$(hyprctl monitors -j | python3 -c 'import json,sys; print(json.load(sys.stdin)[0]["name"])')
		warn "  $RDP_OUTPUT not connected; sharing $output instead (change in the bar panel)."
	fi
	read -r -s -p "  RDP password for $RDP_USER (Enter = generate a new one): " pw </dev/tty
	echo >&2
	if [[ -z $pw ]]; then
		pw=$(python3 "$CTL" generate-password | python3 -c 'import json,sys; print(json.load(sys.stdin)["password"])')
		(umask 077 && printf '%s\n' "$pw" >"$HOME/rdp-iphone-password.txt")
		warn "  Generated: saved to ~/rdp-iphone-password.txt — move it to your password manager, then delete the file."
	fi
	result=$(RDP_PW=$pw TS_IP=$TS_IP OUT=$output python3 -c '
import json, os
print(json.dumps(dict(address=os.environ["TS_IP"], port='"$RDP_PORT"', username="'"$RDP_USER"'",
    mode="monitor", output=os.environ["OUT"], fps='"$RDP_FPS"', audio='"${RDP_AUDIO^}"',
    autostart=False, password=os.environ["RDP_PW"])))' | python3 "$CTL" configure)
	unset pw
	grep -q '"ok": true' <<<"$result" || die "  configure failed: $result"
	ok "configured on $TS_IP:$RDP_PORT as $RDP_USER, sharing $output"
fi
python3 "$CTL" enable >/dev/null
sleep 4
status=$(python3 "$CTL" status)
state=$(python3 -c 'import json,sys; print(json.loads(sys.argv[1]).get("state","?"))' "$status")
fp=$(python3 -c 'import json,sys; print(json.loads(sys.argv[1]).get("fingerprint",""))' "$status")
[[ $state == Ready || $state == Connected ]] || warn "  Remote Desktop state: $state (check the bar panel)"
ok "Remote Desktop: $state on $TS_IP:$RDP_PORT (starts at every desktop login)"

cat >&2 <<EOF

All set. On the iPhone (Tailscale on):
  SSH: ssh $USER@$TS_IP
  RDP: Windows App → Add PC → $TS_IP, user $RDP_USER
       Certificate SHA-256 to compare on first connect:
       $fp
Optional extra layer: the Tailscale ACL in remote-access/README.md.
EOF
